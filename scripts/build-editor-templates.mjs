// Pixelite visual editor: compile the property-panel templates ({% %} micro-templates taken from VvvebJs editor.html, Apache-2.0) into plain JS functions.
// VvvebJs compiles them in the browser with new Function(), which needs script-src 'unsafe-eval'. Compiling here keeps the editor page's CSP strict.
//   node scripts/build-editor-templates.mjs          → writes public/assets/editor/px-templates.generated.js
// Syntax: {% js %} runs JS · {%= expr %} prints expr HTML-ESCAPED (upstream printed it raw) · {%# expr %} prints raw (trusted static text only).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = fs.readFileSync(path.join(root, 'scripts/editor/templates.html'), 'utf8');
const out = path.join(root, 'public/assets/editor/px-templates.generated.js');

function compile(body) {
  const text = body.replace(/<!--[\s\S]*?-->/g, '').replace(/\s+/g, ' ');
  let code = '', last = 0, m;
  const re = /\{%([=#]?)([\s\S]*?)%\}/g;
  const lit = (t) => (t ? `p.push(${JSON.stringify(t)});` : '');
  while ((m = re.exec(text))) {
    code += lit(text.slice(last, m.index));
    code += m[1] === '=' ? `p.push(esc(${m[2]}));` : m[1] === '#' ? `p.push(${m[2]});` : m[2] + '\n';
    last = re.lastIndex;
  }
  code += lit(text.slice(last));
  return `function(obj){var p=[];with(obj){${code}}return p.join("");}`;
}

const blocks = [...src.matchAll(/<script id="([a-z-]+)" type="text\/html">([\s\S]*?)<\/script>/g)];
let js = `/* GENERATED by scripts/build-editor-templates.mjs from scripts/editor/templates.html – do not edit.
 * The templates derive from VvvebJs editor.html (Apache-2.0, https://github.com/givanz/VvvebJs, commit 1acbab7ebfe3e7b004f1f18c039d26550fc04bd8),
 * modified by Pixelite: precompiled to functions (no eval), {%= %} escapes by default, icon/remote-asset parts removed.
 * Plain functions only: this file needs no 'unsafe-eval'. */
(function () {
  var esc = function (v) { return String(v == null ? "" : v).replace(/[&<>"']/g, function (c) { return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]; }); };
  window.PixeliteTemplates = {
`;
for (const [, id, body] of blocks) js += `    ${JSON.stringify(id)}: (${compile(body)}),\n`;
js += '  };\n  // the templates reference esc() as a free variable\n  window.PixeliteTemplatesEsc = esc;\n})();\n';
// make esc visible to the compiled functions: they are defined inside the IIFE above, so it is in scope.
fs.writeFileSync(out, js);
console.log(`${blocks.length} templates → ${path.relative(root, out)} (${js.length} bytes)`);
